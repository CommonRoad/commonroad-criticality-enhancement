def convergence_plot(iterations, bo_mean, sa_mean, gr_mean):
    """
    Plots convergence curves for BO, SA, and Gradient methods
    and exports to TikZ format.

    Parameters:
    - iterations (list or np.ndarray): Iteration numbers.
    - bo_mean, sa_mean, gr_mean (np.ndarray): Mean % values for each method.
    """
    plt.figure(figsize=(12, 4))
    plt.plot(
        iterations,
        bo_mean,
        label="BO",
        color="orange",
    )
    plt.plot(
        iterations,
        sa_mean,
        label="SA",
        color="green",
    )
    plt.plot(
        iterations,
        gr_mean,
        label="Gradient",
        color="blue",
    )

    plt.xlabel("Iteration")
    plt.ylabel("Mean Area (%)")
    plt.legend()
    plt.grid(True)
    plt.tight_layout()
    plt.margins(x=0)

    matplot2tikz.save("convergence_plot.tex", axis_width="12cm", axis_height="6cm")
    plt.show()


